-- 在 Supabase 项目的 SQL Editor 中完整运行
create table if not exists public.travel_cities (
  id uuid primary key,
  room_code text not null,
  name text not null,
  lat double precision not null,
  lng double precision not null,
  status text default '考虑中',
  transport numeric,
  hotel numeric,
  other_cost numeric,
  attractions jsonb default '[]'::jsonb,
  notes text default '',
  votes integer default 0,
  created_at timestamptz default now()
);
create table if not exists public.travel_comments (
  id bigint generated by default as identity primary key,
  room_code text not null,
  nickname text default '旅行伙伴',
  body text not null,
  created_at timestamptz default now()
);
alter table public.travel_cities enable row level security;
alter table public.travel_comments enable row level security;

-- 简易房间码协作：知道房间代号的人可以查看和编辑该房间内容。
-- 不要在此版本填写个人隐私、证件或支付信息；正式公开运营前应增加账号认证和更严格权限。
create policy "room members can read cities" on public.travel_cities for select to anon, authenticated using (true);
create policy "room members can add cities" on public.travel_cities for insert to anon, authenticated with check (true);
create policy "room members can edit cities" on public.travel_cities for update to anon, authenticated using (true) with check (true);
create policy "room members can delete cities" on public.travel_cities for delete to anon, authenticated using (true);

create policy "room members can read comments" on public.travel_comments for select to anon, authenticated using (true);
create policy "room members can add comments" on public.travel_comments for insert to anon, authenticated with check (true);

-- 开启实时变更推送
alter publication supabase_realtime add table public.travel_cities;
alter publication supabase_realtime add table public.travel_comments;
